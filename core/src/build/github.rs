//! Runs a build on GitHub Actions: pushes a copy of the project plus a generated workflow to
//! a branch of a build repository, waits for the run, and downloads its logs.

use super::local::{copy_project, junit_counts, new_build_dir, newest_crash};
use super::logs::analyze_log;
use super::{
    BuildBackend, BuildError, BuildOutcome, BuildRequest, Stage, StageResult, StageStatus,
};
use crate::app::Secret;
use serde::Deserialize;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::{Duration, Instant};

const WORKFLOW: &str = r#"# Generated by UMMP (`ummp build`). Runs untrusted mod code only on this disposable runner:
# no secrets, read-only token.
name: ummp-build
on:
  push:
    branches: ['ummp/**']
permissions:
  contents: read
jobs:
  build:
    runs-on: ubuntu-latest
    timeout-minutes: 90
    steps:
      - uses: actions/checkout@v4
      # Fails the run if gradle/wrapper/gradle-wrapper.jar is not an official Gradle wrapper.
      - uses: gradle/actions/wrapper-validation@v4
      - uses: actions/setup-java@v4
        with:
          distribution: temurin
          java-version: '@JAVA@'
      - name: Build, test, start server
        shell: bash
        run: |
          mkdir -p ummp-out
          G=gradle; if [ -f gradlew ]; then chmod +x gradlew; G=./gradlew; fi
          status=passed
          stage() {
            name=$1; shift
            if [ "$status" != passed ]; then
              echo "{\"stage\":\"$name\",\"status\":\"skipped\"}" >> ummp-out/stages.jsonl; return
            fi
            if "$@" > "ummp-out/$name.log" 2>&1; then s=passed; else
              s=failed; status=failed
              # Artifact storage can be unreachable for the caller; keep the error in the job log.
              echo "UMMP-LOG-BEGIN $name"; tail -n 80 "ummp-out/$name.log"; echo "UMMP-LOG-END $name"
            fi
            echo "{\"stage\":\"$name\",\"status\":\"$s\"}" >> ummp-out/stages.jsonl
          }
          server() {
            mkdir -p run && echo eula=true > run/eula.txt && mkfifo ummp-stdin
            $G runServer --no-daemon --console=plain < ummp-stdin &
            exec 3> ummp-stdin
            for i in $(seq @TIMEOUT@); do
              grep -q 'Done (' ummp-out/server.log && break
              jobs %1 > /dev/null 2>&1 || break
              sleep 1
            done
            echo stop >&3
            for i in $(seq 30); do jobs %1 > /dev/null 2>&1 || break; sleep 1; done
            kill %1 2> /dev/null; exec 3>&-
            grep -q 'Done (' ummp-out/server.log
          }
@STAGES@
          jq -s . ummp-out/stages.jsonl > ummp-out/stages.json
          echo "UMMP-STAGES $(jq -c . ummp-out/stages.json)"
          cp -r build/test-results ummp-out/ 2> /dev/null || true
          cp -r run/crash-reports ummp-out/ 2> /dev/null || true
      - uses: actions/upload-artifact@v4
        if: always()
        with:
          name: ummp-build
          path: ummp-out/
"#;

const NO_GH: &str =
    "Install the GitHub CLI and run `gh auth login`, or build on this machine with --local";

#[derive(Deserialize)]
struct Run {
    #[serde(rename = "databaseId")]
    id: u64,
    status: String,
}

#[derive(Deserialize)]
struct StageLine {
    stage: String,
    status: String,
}

#[derive(Debug, Clone)]
pub struct GithubBackend {
    /// `owner/name` of the build repository.
    pub repo: String,
    pub gh: PathBuf,
    pub git: PathBuf,
    pub poll: Duration,
    pub workdir: PathBuf,
    /// Optional credential supplied by the desktop OS keyring; redacted in Debug.
    pub token: Option<Secret>,
}

/// The workflow that runs `stages` with Java `java`, each limited to `timeout_secs`.
#[must_use]
pub fn workflow_yaml(java: u32, stages: &[Stage], timeout_secs: u64) -> String {
    let lines: Vec<String> = stages
        .iter()
        .map(|s| match s {
            Stage::Build => format!(
                "          stage build timeout {timeout_secs} $G build -x test --no-daemon --console=plain"
            ),
            Stage::Test => format!(
                "          stage test timeout {timeout_secs} $G test --no-daemon --console=plain"
            ),
            Stage::Server => "          stage server server".to_string(),
        })
        .collect();
    WORKFLOW
        .replace("@JAVA@", &java.to_string())
        .replace("@TIMEOUT@", &timeout_secs.to_string())
        .replace("@STAGES@", &lines.join("\n"))
}

fn status_of(s: &str) -> StageStatus {
    match s {
        "passed" => StageStatus::Passed,
        "skipped" => StageStatus::Skipped,
        "timed_out" => StageStatus::TimedOut,
        _ => StageStatus::Failed,
    }
}

/// Runs a trusted local tool (`gh`, `git`) and returns its stdout.
fn tool(program: &Path, args: &[&str], cwd: &Path) -> Result<String, BuildError> {
    tool_with_token(program, args, cwd, None)
}

fn tool_with_token(
    program: &Path,
    args: &[&str],
    cwd: &Path,
    token: Option<&Secret>,
) -> Result<String, BuildError> {
    let mut command = Command::new(program);
    if let Some(token) = token {
        command.env("GH_TOKEN", token.expose());
    }
    let out =
        command.args(args).current_dir(cwd).output().map_err(|e| {
            BuildError::Tool(format!("cannot run {}: {e}. {NO_GH}", program.display()))
        })?;
    if !out.status.success() {
        return Err(BuildError::Tool(format!(
            "`{} {}` failed: {}",
            program.display(),
            args.join(" "),
            String::from_utf8_lossy(&out.stderr).trim()
        )));
    }
    Ok(String::from_utf8_lossy(&out.stdout).into_owned())
}

#[derive(Deserialize)]
struct Jobs {
    jobs: Vec<Job>,
}

#[derive(Deserialize)]
struct Job {
    id: u64,
}

/// The JSON after the `UMMP-STAGES ` marker the workflow prints to its log.
fn stages_line(log: &str) -> Option<String> {
    log.lines()
        .filter_map(|l| l.split_once("UMMP-STAGES ").map(|(_, rest)| rest.trim()))
        .find(|rest| rest.starts_with('['))
        .map(String::from)
}

impl GithubBackend {
    /// Stage results from the job log; the log is saved as `<art>/job.log` (it holds the
    /// tail of each failed stage's log).
    fn stages_from_job_log(&self, run_id: &str, dir: &Path, art: &Path) -> Option<String> {
        let jobs = tool_with_token(
            &self.gh,
            &[
                "api",
                &format!("repos/{}/actions/runs/{run_id}/jobs", self.repo),
            ],
            dir,
            self.token.as_ref(),
        )
        .ok()?;
        let job = serde_json::from_str::<Jobs>(&jobs).ok()?.jobs.first()?.id;
        let log = tool_with_token(
            &self.gh,
            &[
                "api",
                &format!("repos/{}/actions/jobs/{job}/logs", self.repo),
            ],
            dir,
            self.token.as_ref(),
        )
        .ok()?;
        if std::fs::create_dir_all(art).is_ok() {
            // Best effort: without the saved log, failed stages just have no error details.
            let _ = std::fs::write(art.join("job.log"), &log);
        }
        stages_line(&log)
    }

    fn wait_for_run(&self, branch: &str, dir: &Path, limit: Duration) -> Result<u64, BuildError> {
        let deadline = Instant::now() + limit;
        loop {
            let out = tool_with_token(
                &self.gh,
                &[
                    "run",
                    "list",
                    "-R",
                    &self.repo,
                    "--branch",
                    branch,
                    "--json",
                    "databaseId,status,conclusion",
                    "--limit",
                    "1",
                ],
                dir,
                self.token.as_ref(),
            )?;
            let runs: Vec<Run> = serde_json::from_str(&out)
                .map_err(|e| BuildError::Tool(format!("unexpected `gh run list` output: {e}")))?;
            if let Some(r) = runs.first().filter(|r| r.status == "completed") {
                return Ok(r.id);
            }
            if Instant::now() > deadline {
                return Err(BuildError::Tool(format!(
                    "no finished run on {}/{branch} after {}s",
                    self.repo,
                    limit.as_secs()
                )));
            }
            std::thread::sleep(self.poll);
        }
    }
}

impl BuildBackend for GithubBackend {
    fn run(&self, req: &BuildRequest) -> Result<BuildOutcome, BuildError> {
        let here = Path::new(".");
        tool_with_token(&self.gh, &["--version"], here, self.token.as_ref())?;
        // Checks login and access to the build repo in one REST call.
        let repo_api = format!("repos/{}", self.repo);
        tool_with_token(
            &self.gh,
            &["api", &repo_api, "--jq", ".full_name"],
            here,
            self.token.as_ref(),
        )
        .map_err(|e| {
            BuildError::Tool(format!(
                "Cannot reach build repo {} with the GitHub CLI ({e}). Create the repo and run \
                 `gh auth login`, or build on this machine with --local",
                self.repo
            ))
        })?;

        let dir = new_build_dir(&self.workdir, &req.mod_name)?;
        copy_project(&req.project, &dir)?;
        // The mod's own workflows must not run (they may expect secrets or publish).
        let workflows = dir.join(".github/workflows");
        if workflows.exists() {
            std::fs::remove_dir_all(&workflows)?;
        }
        std::fs::create_dir_all(&workflows)?;
        std::fs::write(
            workflows.join("ummp-build.yml"),
            workflow_yaml(req.java.unwrap_or(21), &req.stages, req.timeout.as_secs()),
        )?;

        let branch = format!(
            "ummp/{}",
            dir.file_name().unwrap_or_default().to_string_lossy()
        );
        let url = format!("https://github.com/{}.git", self.repo);
        let refspec = format!("HEAD:refs/heads/{branch}");
        let helper = format!(
            "credential.helper=!'{}' auth git-credential",
            self.gh.display()
        );
        tool(&self.git, &["init", "-q"], &dir)?;
        tool(&self.git, &["add", "-A"], &dir)?;
        tool(
            &self.git,
            &[
                "-c",
                "user.name=ummp",
                "-c",
                "user.email=ummp@users.noreply.github.com",
                "commit",
                "-q",
                "-m",
                "ummp build",
            ],
            &dir,
        )?;
        tool_with_token(
            &self.git,
            &[
                "-c",
                "credential.helper=",
                "-c",
                &helper,
                "push",
                "-q",
                "--force",
                &url,
                &refspec,
            ],
            &dir,
            self.token.as_ref(),
        )?;

        let stage_count = u32::try_from(req.stages.len()).unwrap_or(u32::MAX);
        let limit = req.timeout * (stage_count + 1) + Duration::from_mins(10);
        let id = self.wait_for_run(&branch, &dir, limit)?.to_string();
        let art = dir.join("ummp-artifact");
        let art_s = art.to_string_lossy().into_owned();
        let downloaded = tool_with_token(
            &self.gh,
            &[
                "run",
                "download",
                &id,
                "-R",
                &self.repo,
                "-n",
                "ummp-build",
                "-D",
                &art_s,
            ],
            &dir,
            self.token.as_ref(),
        );
        let json = match downloaded {
            Ok(_) => std::fs::read_to_string(art.join("stages.json")).ok(),
            // Artifact storage can be blocked by a proxy; the job log (REST) still has the
            // stage results, though not the per-stage logs.
            Err(e) => {
                eprintln!("warning: artifact download failed, reading stage results from the job log: {e}");
                self.stages_from_job_log(&id, &dir, &art)
            }
        }
        .ok_or_else(|| {
            BuildError::Tool(format!(
                "run {id} produced no stage results; see https://github.com/{}/actions/runs/{id}",
                self.repo
            ))
        })?;
        let lines: Vec<StageLine> = serde_json::from_str(&json)
            .map_err(|e| BuildError::Tool(format!("bad stages.json: {e}")))?;
        let stages = req
            .stages
            .iter()
            .map(|&stage| {
                let status = lines
                    .iter()
                    .find(|l| l.stage == stage.name())
                    .map_or(StageStatus::Skipped, |l| status_of(&l.status));
                let mut log = art.join(format!("{}.log", stage.name()));
                let job_log = art.join("job.log");
                if !log.exists() && status == StageStatus::Failed && job_log.exists() {
                    log = job_log;
                }
                let errors = std::fs::read_to_string(&log)
                    .map(|t| analyze_log(&t))
                    .unwrap_or_default();
                StageResult {
                    stage,
                    status,
                    log: if log.exists() { log } else { PathBuf::new() },
                    errors,
                }
            })
            .collect();
        Ok(BuildOutcome {
            stages,
            tests: junit_counts(&art.join("test-results")),
            crash: newest_crash(&art.join("crash-reports")),
            workdir: dir,
        })
    }
}
